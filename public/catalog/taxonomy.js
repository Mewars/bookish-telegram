export const foodSubcategories = catalogGroups.flatMap(group=>group.items)
  .find(parent=>parent.name==='Где поесть').subs;
export const normalizeCategory = value=>String(value||'').toLocaleLowerCase('ru').replaceAll('ё','е').trim();
const foodTypes=[
 ['pizza-sushi',/пицц|суши|роллы/],['streetfood',/бургер|стритфуд|фастфуд|закусочн|шаурм/],
 ['canteen',/столов/],['bakery',/пекар|кондитер|булоч/],['restaurant',/ресторан/],
 ['bar',/бары|бар |^бар$|паб/],['delivery',/доставк/],['cafe',/кафе|кофейн/]
];
export function isFoodCategory(value){return /кафе|кофейн|ресторан|столов|пицц|суши|пекар|кондитер|бургер|стритфуд|фастфуд|общепит|еда|где поесть|доставка еды|бар(?:ы|$|\s)|паб/.test(normalizeCategory(value))}
export function foodSubcategory(item){
 if(!isFoodCategory(item.category))return null;
 const pieces=String(item.category).split(' / ');
 const explicit=normalizeCategory(pieces.slice(1).join(' / ')||item.category);
 const saved=pieces.length>1&&foodSubcategories.find(sub=>normalizeCategory(sub.name)===explicit);
 if(saved)return saved;
 // A saved, specific category always wins over a venue name. Legacy "Кафе"
 // is a broad bucket, not proof that a restaurant is a cafe.
 let key;
 if(pieces.length>1||!['кафе','где поесть','общепит','еда'].includes(explicit))
  key=foodTypes.find(([,pattern])=>pattern.test(explicit))?.[0];
 if(!key){
  const title=normalizeCategory(item.title);
  // Only the explicit format at the beginning of a title is considered. Menu
  // keywords, brand names and mentions of delivery in descriptions are ignored.
  const declared=title.match(/^(?:кафе|кофейня|ресторан|столовая|пиццерия|бургерная|пекарня|кондитерская|закусочная|бар|паб|доставка еды)(?=\s|[«"“])/u)?.[0];
  if(declared)key=foodTypes.find(([,pattern])=>pattern.test(declared))?.[0];
 }
 if(!key&&/^[^—\n]{1,100}\s+[—–-]\s+(?:это\s+)?служба доставки/u.test(normalizeCategory(item.description)))key='delivery';
 return foodSubcategories.find(sub=>sub.foodKey===(key||'unclassified'));
}
export function categoryParts(item){
 const food=foodSubcategory(item);
 if(food)return {category:'Кафе',subcategory:food.name};
 const [category,...rest]=String(item.category||'').split(' / ');
 return {category,subcategory:rest.join(' / ')};
}
export function savedFoodCategory(key){
 const sub=foodSubcategories.find(entry=>entry.foodKey===key);
 return sub?'Кафе / '+sub.name:'Кафе';
}
