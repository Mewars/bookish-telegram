"""Actual stories UI and canvas with synthetic in-memory API; SQL rights are tested separately."""
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
ORIGIN='http://127.0.0.1:4178'
Path('qa-screenshots').mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch()
 for width,height in [(390,844),(1440,900)]:
  context=browser.new_context(viewport={'width':width,'height':height},locale='ru-RU',reduced_motion='reduce')
  context.route('**/*',lambda r:r.continue_() if r.request.url.startswith(ORIGIN+'/') else r.abort())
  page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.goto(ORIGIN+'/tests/stories-live-fixture.html')
  expect(page.get_by_role('heading',name='Истории рядом',exact=True)).to_be_visible()
  expect(page.get_by_role('button',name='Модерация историй',exact=True)).to_have_count(0)
  page.get_by_role('button',name='Добавить историю',exact=True).click()
  expect(page.get_by_role('link',name='Войти на сайт',exact=True)).to_be_visible()
  page.get_by_role('button',name='Закрыть',exact=True).click()
  page.get_by_label('Тестовый пользователь',exact=True).select_option('resident')
  expect(page.get_by_role('button',name='Мои истории',exact=True)).to_be_visible()
  page.get_by_role('button',name='Добавить историю',exact=True).click()
  form=page.get_by_role('dialog',name='Добавить историю',exact=True)
  form.get_by_label('Фото · JPG, PNG или WebP, до 10 МБ',exact=True).set_input_files('public/brand/discovery/park.webp')
  form.get_by_label('Подпись',exact=True).fill('Моя история <script>без HTML</script>')
  form.get_by_role('button',name='Отправить на модерацию',exact=True).click()
  expect(form).to_have_count(0)
  expect(page.get_by_role('button',name='История: Житель',exact=True)).to_have_count(0)
  page.get_by_role('button',name='Мои истории',exact=True).click()
  mine=page.get_by_role('dialog',name='Мои истории',exact=True)
  expect(mine.get_by_text('На проверке',exact=True)).to_be_visible();mine.get_by_role('button',name='Закрыть',exact=True).click()
  page.get_by_label('Тестовый пользователь',exact=True).select_option('editor')
  page.get_by_role('button',name='Модерация историй',exact=True).click()
  manager=page.get_by_role('dialog',name='Модерация историй',exact=True)
  manager.get_by_role('button',name='Открыть историю',exact=True).click()
  viewer=page.get_by_role('dialog',name='Просмотр истории',exact=True)
  expect(viewer.get_by_text('Моя история <script>без HTML</script>',exact=True)).to_be_visible()
  viewer.get_by_role('button',name='Опубликовать',exact=True).click();expect(viewer).to_have_count(0)
  expect(manager.get_by_text('Здесь пока нет историй.',exact=True)).to_be_visible()
  manager.get_by_role('button',name='Закрыть',exact=True).click()
  expect(page.get_by_role('button',name='История: Житель',exact=True)).to_be_visible()
  page.get_by_label('Тестовый пользователь',exact=True).select_option('guest')
  expect(page.get_by_role('button',name='Мои истории',exact=True)).to_have_count(0)
  page.get_by_role('button',name='История: Житель',exact=True).click()
  expect(viewer.get_by_text('Моя история <script>без HTML</script>',exact=True)).to_be_visible()
  expect(viewer.locator('script')).to_have_count(0)
  expect(viewer.get_by_role('button',name='Опубликовать',exact=True)).to_have_count(0)
  expect(viewer.get_by_role('button',name='Удалить историю',exact=True)).to_have_count(0)
  page.screenshot(path=f'qa-screenshots/stories-live-viewer-{width}.png',full_page=True)
  viewer.get_by_role('button',name='Закрыть историю',exact=True).click()
  page.get_by_label('Тестовый город',exact=True).select_option('Город Б')
  expect(page.get_by_role('button',name='История: Житель',exact=True)).to_have_count(0)
  page.get_by_label('Тестовый пользователь',exact=True).select_option('editor')
  expect(page.get_by_role('button',name='Мои истории',exact=True)).to_be_visible()
  expect(page.get_by_role('button',name='Модерация историй',exact=True)).to_have_count(0)
  assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+2')
  assert not errors,errors
  context.close()
 browser.close()
print('PASS: resident canvas upload -> pending -> city moderation -> guest view; city/auth isolation and literal caption')
