"""Fixed-date public event UI with local fixtures and no production writes."""
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
ORIGIN='http://127.0.0.1:4178'
Path('qa-screenshots').mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch()
 for width,height in [(390,844),(1440,900)]:
  context=browser.new_context(viewport={'width':width,'height':height},locale='ru-RU',timezone_id='America/New_York',reduced_motion='reduce')
  def route(r):
   if r.request.url.startswith(ORIGIN+'/src/lib/supabase.ts'):r.fulfill(content_type='text/javascript',body="import {c} from '/tests/home-life-sdk.mjs';export const supabase=c();")
   elif r.request.url.startswith(ORIGIN+'/'):r.continue_()
   else:r.abort()
  context.route('**/*',route)
  page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.clock.install(time='2026-10-25T12:00:00Z')
  page.goto(ORIGIN+'/tests/events-fixture.html#/home?city=Енисейск')
  expect(page.locator('.city-cover .life-eyebrow,.city-cover .life-cover-caption')).to_have_count(0)
  expect(page.get_by_role('heading',name='Енисейск',exact=True)).to_be_visible()
  page.get_by_role('button',name='Сегодня',exact=True).click()
  expect(page.locator('#city-selections .card')).to_have_count(1)
  expect(page.get_by_role('heading',name='День автомобилиста',exact=True)).to_be_visible()
  expect(page.get_by_role('heading',name='Работающее кафе',exact=True)).to_have_count(0)
  page.wait_for_function("document.querySelector('.card-image img')?.naturalWidth>0")
  assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+2')
  page.screenshot(path=f'qa-screenshots/today-events-{width}.png',full_page=True)
  page.get_by_role('button',name='Открыть афишу',exact=True).click()
  expect(page.locator('.card-grid .card')).to_have_count(5)
  page.get_by_role('button',name='Завтра',exact=True).click()
  expect(page.locator('.card-grid .card')).to_have_count(2)
  page.get_by_role('button',name='Открыть: Спектакль «Горе от ума»',exact=True).click()
  expect(page.get_by_role('link',name='Купить билеты',exact=False)).to_have_attribute('href','https://quicktickets.ru/motygino-dramteatr/s823')
  expect(page.locator('#detail-contacts')).to_contain_text('26 октября')
  page.get_by_role('button',name='Назад в афишу',exact=True).click()
  page.get_by_role('button',name='Все даты',exact=True).click()
  page.clock.set_system_time('2026-10-28T16:59:30Z')
  page.clock.run_for(30000)
  expect(page.get_by_role('heading',name='Кино в «Родине»',exact=True)).to_have_count(0)
  expect(page.get_by_role('heading',name='Спектакль «Горе от ума»',exact=True)).to_have_count(0)
  expect(page.locator('.card-grid .card')).to_have_count(2)
  page.get_by_role('button',name='На главную',exact=True).click()
  page.get_by_role('button',name='Сегодня',exact=True).click()
  expect(page.get_by_role('heading',name='На сегодня событий пока нет',exact=True)).to_be_visible()
  expect(page.get_by_role('heading',name='День автомобилиста',exact=True)).to_have_count(0)
  page.get_by_role('button',name='Вся афиша',exact=True).click()
  expect(page.locator('.card-grid .card')).to_have_count(2)
  page.clock.set_system_time('2026-11-15T17:00:00Z');page.clock.run_for(30000)
  expect(page.get_by_role('heading',name='Афиша пока пуста',exact=True)).to_be_visible()
  page.get_by_label('Тестовый город',exact=True).select_option('Лесосибирск')
  page.get_by_role('button',name='Открыть афишу',exact=True).click()
  expect(page.locator('.card-grid .card')).to_have_count(0)
  assert not errors,errors
  print('PASS',width,'today agenda, poster images, tomorrow range, ticket, midnight expiration, empty city')
  context.close()
 browser.close()
